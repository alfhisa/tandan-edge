"""
tandan_paths.py — single place for every path the scripts need.

All scripts import this module, so the repository works from any clone location
and from any working directory. Override the defaults with environment variables:

  TANDAN_DATA     folder of the YOLO-format MOPAD Site 2 dataset
                  (must contain train/images, train/labels, val/images, val/labels)
                  default: <repo>/datasets/mopad_site2
  TANDAN_RUNS     where training/evaluation runs are written
                  default: <repo>/runs
"""

import os
from pathlib import Path

REPO = Path(__file__).resolve().parent
DATASET_DIR = Path(os.environ.get("TANDAN_DATA", REPO / "datasets" / "mopad_site2")).resolve()
RUNS_DIR = Path(os.environ.get("TANDAN_RUNS", REPO / "runs")).resolve()
RESULTS_DIR = REPO / "results"
MODEL_CONFIGS = REPO / "model_configs"
WEIGHTS_DIR = REPO / "weights"
PRETRAINED_DIR = WEIGHTS_DIR / "pretrained"

CLASS_NAMES = ["dead", "healthy", "mismanaged", "smallish", "yellowish"]

# Deployed model (train 768, run at 704 on the Jetson). Download from the GitHub release.
FINAL_WEIGHTS = WEIGHTS_DIR / "tandan-edge_yolo11n_train768.pt"


def _write_data_yaml():
    """Write the dataset YAML with an absolute dataset path and return its path."""
    out = RUNS_DIR / "_data" / "mopad_site2.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    text = (
        "# generated by tandan_paths.py (template: data/mopad_site2.yaml)\n"
        "path: %s\n"
        "train: train/images\n"
        "val: val/images\n"
        "names:\n%s"
        % (DATASET_DIR.as_posix(), "".join("  %d: %s\n" % (i, n) for i, n in enumerate(CLASS_NAMES)))
    )
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    return out


DATASET_YAML = _write_data_yaml()


# Folder names of the original research workspace -> location in this repository.
# The result CSVs keep the original run paths (column "path"/"weights"), and the
# figure/table scripts were written against that layout; P() translates them.
_LEGACY = [
    ("jetson_results/trt_results", RESULTS_DIR / "jetson" / "trt_resolution"),
    ("jetson_results/onnx_cmp_logs", RESULTS_DIR / "jetson" / "base_models_640"),
    ("jetson_results/thermal_results_30min", RESULTS_DIR / "jetson" / "thermal_30min"),
    ("jetson_results/thermal_results", RESULTS_DIR / "jetson" / "thermal_5min"),
    ("jetson_results", RESULTS_DIR / "jetson"),
    ("reeval", RESULTS_DIR / "reeval"),
    ("tables", RESULTS_DIR / "tables"),
    ("figures", RESULTS_DIR / "figures"),
    ("site_2_only_dataset", DATASET_DIR),
    ("runs", RUNS_DIR),
]
_LEGACY_RUN_PARENTS = ("exp-journal-1/", "tandan-yolo/runs/")


def P(path):
    """Map a path of the original workspace layout to this repository (see _LEGACY)."""
    s = str(path)
    if s.startswith(_LEGACY_RUN_PARENTS):
        # per-run records (args.yaml, results.csv, *_metrics.json) are in results/runs/<run>/
        tail = s.split("/")
        if "weights" in tail:  # a checkpoint: look for it in runs/
            i = tail.index("weights")
            return str(RUNS_DIR / "/".join(tail[i - 1:]))
        name = tail[-1] if "." not in tail[-1] else tail[-2]
        rest = [] if "." not in tail[-1] else [tail[-1]]
        return str(RESULTS_DIR.joinpath("runs", name, *rest))
    for old, new in _LEGACY:
        if s == old or s.startswith(old + "/"):
            return str(new) + s[len(old):]
    return s


def pretrained(name):
    """Path to an Ultralytics COCO checkpoint (e.g. 'yolo11n.pt'); downloaded on first use."""
    PRETRAINED_DIR.mkdir(parents=True, exist_ok=True)
    p = PRETRAINED_DIR / name
    if not p.exists():
        from ultralytics.utils.downloads import attempt_download_asset
        got = Path(attempt_download_asset(str(p)))
        if got.resolve() != p.resolve() and got.exists():
            got.replace(p)
    return p
